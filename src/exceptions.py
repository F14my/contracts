class TaskError(Exception):
    """Базовое исключение задачи"""
    pass

class TaskInvalidStateError(TaskError):
    """
    Выбрасывается при нарушении инвариантов состояния объекта.

    Примеры:
        - Недопустимый переход статуса
        - Попытка изменить неизменяемый атрибут
        - Нарушение бизнес-логики
    """
    pass

class InvalidAttributeError(TaskError):
    """
    Выбрасывается при нарушении валидации атрибута.

    Примеры:
        - Неверный тип данных
        - Значение вне допустимого диапазона
        - Нарушение формата
    """
    pass
